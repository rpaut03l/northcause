import {
  getIncident,
  getInvestigationDetail,
  listApprovals,
  listCheckRuns,
  listDrafts,
  listEvidence,
  listInvestigations,
  listTimeline,
} from './workflow';

function md(s: string): string {
  // Neutralise Markdown/HTML control characters from untrusted text so the report renders as text.
  return s.replace(/[\\`*_{}[\]<>#|!]/g, (c) => `\\${c}`).replace(/\r?\n/g, ' ');
}

/** Builds a Markdown incident report from stored records only. */
export async function buildReport(db: D1Database, tenantId: string, incidentId: string): Promise<string | null> {
  const inc = await getIncident(db, tenantId, incidentId);
  if (!inc) return null;
  const [evidence, timeline, invs, drafts, approvals, checks] = await Promise.all([
    listEvidence(db, tenantId, incidentId),
    listTimeline(db, tenantId, incidentId),
    listInvestigations(db, tenantId, incidentId),
    listDrafts(db, tenantId, incidentId),
    listApprovals(db, tenantId, incidentId),
    listCheckRuns(db, tenantId, incidentId),
  ]);
  const out: string[] = [];
  out.push(`# Incident report: ${md(inc.title)}`, '');
  out.push(`- Incident ID: ${inc.id}`, `- Service: ${md(inc.service)}`, `- Severity: ${inc.severity}`, `- Status: ${inc.status}`);
  out.push(`- Created: ${inc.created_at}`, `- Report generated: ${new Date().toISOString()}`, '');
  out.push('> Generated by Northcause (pilot). Findings are limited to the evidence listed below. Hypotheses are not proof; checks show whether failure signals were absent from uploaded post-fix evidence, not a guarantee.', '');
  if (inc.summary) out.push('## Summary', '', md(inc.summary), '');

  out.push('## Evidence', '', '| ID | Label | Phase | Format | Size (bytes) | SHA-256 | Redactions | Injection flags |', '|---|---|---|---|---|---|---|---|');
  for (const e of evidence) {
    out.push(`| ${e.id} | ${md(e.label)} | ${e.phase} | ${e.format} | ${e.size_bytes} | ${e.sha256.slice(0, 16)}… | ${e.secrets_redacted} | ${e.injection_flags} |`);
  }
  out.push('');

  out.push('## Timeline (UTC)', '');
  if (!timeline.length) out.push('No timestamped events were found in the evidence.');
  for (const t of timeline.slice(0, 200)) out.push(`- ${t.occurred_at} [${t.kind}] ${md(t.summary)} (${t.evidence_id} L${t.line_no})`);
  if (timeline.length > 200) out.push(`- … ${timeline.length - 200} more events not shown`);
  out.push('');

  const latest = invs[0];
  out.push('## Investigation', '');
  if (!latest) out.push('No investigation has been run.');
  else {
    const d = await getInvestigationDetail(db, tenantId, latest.id);
    out.push(`- Investigation ID: ${latest.id}`, `- Provider: ${md(latest.provider_label)}`, `- External model used: ${latest.external_model_used ? 'yes' : 'no'}`, `- Result: ${latest.status}`, `- Notes: ${md(latest.notes)}`, '');
    for (const kind of ['hypothesis', 'risk'] as const) {
      const claims = d?.claims.filter((c) => c.kind === kind) ?? [];
      if (!claims.length) continue;
      out.push(kind === 'hypothesis' ? '### Ranked hypotheses' : '### Security and policy risks', '');
      for (const c of claims) {
        out.push(`${c.rank}. ${md(c.statement)} — confidence ${c.confidence}, ${c.support.toUpperCase()}`);
        const cits = d?.citations.filter((x) => x.claim_id === c.id) ?? [];
        if (!cits.length) out.push('   - No valid citation. Treat as unsupported.');
        for (const x of cits) out.push(`   - ${x.evidence_id}${x.line_no ? ` L${x.line_no}` : ''}: \`${x.excerpt.replace(/`/g, "'")}\``);
      }
      out.push('');
    }
  }

  out.push('## Remediation drafts and approvals', '');
  if (!drafts.length) out.push('No remediation drafts.');
  for (const dr of drafts) {
    out.push(`### ${md(dr.title)} (${dr.id}) — ${dr.status}`);
    (JSON.parse(dr.steps) as string[]).forEach((s, i) => out.push(`${i + 1}. ${md(s)}`));
    for (const a of approvals.filter((x) => x.draft_id === dr.id)) {
      out.push(`- Decision: ${a.decision} by ${md(a.display_name ?? a.decided_by)} at ${a.created_at}. Reason: ${md(a.reason)}`);
    }
    out.push('');
  }

  out.push('## Post-fix checks', '');
  if (!checks.length) out.push('No checks have been run.');
  for (const c of checks) out.push(`- ${c.created_at} ${md(c.check_name)}: ${c.result.toUpperCase()} — ${md(c.detail)} Evidence: ${(JSON.parse(c.evidence_ids) as string[]).join(', ') || 'none'}`);
  out.push('', '---', 'Northcause — Find it. Fix it. Prove it.');
  return out.join('\n');
}
